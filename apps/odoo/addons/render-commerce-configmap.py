"""Render the optional commerce addon; installation is a separate Odoo operation."""
from pathlib import Path
import yaml
root = Path(__file__).resolve().parent
class Literal(str):
    pass
yaml.SafeDumper.add_representer(Literal, lambda dumper, value: dumper.represent_scalar('tag:yaml.org,2002:str', value, style='|'))
files = sorted(p for p in (root / 'medusa_bridge').rglob('*') if p.suffix in ('.py', '.xml', '.csv'))
manifest = {'apiVersion': 'v1', 'kind': 'ConfigMap', 'metadata': {'name': 'odoo-commerce-addon', 'namespace': 'odoo', 'annotations': {'argocd.argoproj.io/sync-wave': '-1'}}, 'data': {p.relative_to(root / 'medusa_bridge').as_posix().replace('/', '__'): Literal(p.read_text()) for p in files}}
(root.parent / 'commerce-addon.yaml').write_text('# Generated by apps/odoo/addons/render-commerce-configmap.py.\n' + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True))
