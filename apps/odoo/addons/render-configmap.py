"""Regenerate the addon delivery manifest after editing authentik_jit sources."""
from pathlib import Path

import yaml

root = Path(__file__).resolve().parent
files = sorted(p for p in (root / 'authentik_jit').rglob('*') if p.suffix in ('.py', '.xml'))


class Literal(str):
    pass


yaml.SafeDumper.add_representer(Literal, lambda dumper, value: dumper.represent_scalar('tag:yaml.org,2002:str', value, style='|'))
manifest = {
    'apiVersion': 'v1',
    'kind': 'ConfigMap',
    'metadata': {
        'name': 'odoo-authentik-jit-addon',
        'namespace': 'odoo',
        'annotations': {'argocd.argoproj.io/sync-wave': '-1'},
    },
    'data': {p.relative_to(root).as_posix().replace('/', '__'): Literal(p.read_text()) for p in files},
}
(root.parent / 'jit-addon.yaml').write_text(
    '# Generated by apps/odoo/addons/render-configmap.py; edit addon sources there.\n'
    + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True),
)
