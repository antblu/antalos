"""Render the Cal.diy addon ConfigMap; installation is a separate operation."""
from pathlib import Path
import yaml

root = Path(__file__).resolve().parent


class Literal(str):
    pass


yaml.SafeDumper.add_representer(Literal, lambda dumper, value: dumper.represent_scalar(
    'tag:yaml.org,2002:str', value, style='|'))
files = sorted(p for p in (root / 'emiliany_cal_diy').rglob('*')
               if p.suffix in ('.py', '.xml', '.csv') and 'tests' not in p.parts)
manifest = {
    'apiVersion': 'v1',
    'kind': 'ConfigMap',
    'metadata': {'name': 'odoo-cal-diy-addon', 'namespace': 'odoo',
                 'annotations': {'argocd.argoproj.io/sync-wave': '-1'}},
    'data': {p.relative_to(root / 'emiliany_cal_diy').as_posix().replace('/', '__'): Literal(p.read_text()) for p in files},
}
(root.parent / 'cal-diy-addon.yaml').write_text(
    '# Generated by apps/odoo/addons/render-cal-diy-configmap.py.\n'
    + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True))
